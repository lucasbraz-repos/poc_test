def validate_headers(headers):
    def normalized(value):
        return " ".join(str(value or "").split()).casefold()

    differences = {
        k: {"esperado": v, "recebido": headers.get(k)}
        for k, v in COLUMNS.items()
        if normalized(v) != normalized(headers.get(k))
    }
    extra = sorted(set(headers) - set(COLUMNS))
    if differences or extra:
        raise ValueError(
            f"Layout da planilha alterado; revise o contrato: {differences}; extras={extra}"
        )


